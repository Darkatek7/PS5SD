#!/bin/sh
# Turns a file into a C/C++ header:
#
#   static const unsigned char <name>[] = { ... };   // the bytes, plus a final 0
#   static const unsigned int  <name>_len = <size>;  // the size without that 0
#
# usage: scripts/embed-file.sh <input-file> <name> [<output-header>]
#        (no output-header: written to stdout)
#
# Used by the build to embed the web UI (scripts/bundle-webui.sh) into sd-server:
#   scripts/embed-file.sh build/index.html sd_server_index_html build/index_html.h
# and pass -DSD_SERVER_EMBED_INDEX=<that header> to CMake.
#
# POSIX sh + od + awk only (no xxd, no python).

set -eu

if [ $# -lt 2 ] || [ $# -gt 3 ]; then
    echo "usage: $0 <input-file> <name> [<output-header>]" >&2
    exit 2
fi

in=$1
name=$2
out=${3:-}

[ -f "$in" ] || { echo "embed-file: no such file: $in" >&2; exit 1; }
case $name in
    ''|[0-9]*|*[!A-Za-z0-9_]*) echo "embed-file: not a C identifier: $name" >&2; exit 2 ;;
esac

emit() {
    printf '/* Generated by scripts/embed-file.sh from %s. Do not edit. */\n' "$(basename "$in")"
    printf '#pragma once\n\n'
    printf 'static const unsigned char %s[] = {\n' "$name"
    LC_ALL=C od -An -v -tu1 "$in" | LC_ALL=C awk '
        { for (i = 1; i <= NF; i++) { printf "%s%s", $i, ","; if (++n % 16 == 0) printf "\n" } }
        END { printf "0\n" }'
    printf '};\n'
    printf 'static const unsigned int %s_len = %s;\n' "$name" "$(wc -c < "$in" | tr -d ' ')"
}

if [ -n "$out" ]; then
    tmp="$out.tmp.$$"
    emit > "$tmp"
    mv "$tmp" "$out"
else
    emit
fi
